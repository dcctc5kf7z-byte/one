export function assemblePrompt(layerIds: string[]): string {
  const layerMap: Record<string, string> = {
    "L0": L0_CORE_IDENTITY,
    "L1": L1_STATE_DETECTION,
    "L2": L2_STATE_XYZ_MAPPING,
    "L3": L3_FULL_DIAGNOSIS,
    "L4": L4_FAULT_HANDLING,
  };

  const parts: string[] = [ROUTE_QUICK_REF]; // FIX-09: 首因效应速查表置于 Prompt 最前端
  for (const id of layerIds) {
    const content = layerMap[id];
    if (content) {
      parts.push(content);
    }
  }

  return parts.join("\n\n");
}
